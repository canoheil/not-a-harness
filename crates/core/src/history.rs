//! Conversation history persistence.
//!
//! Every interactive conversation is saved as one plain-text record under
//! `~/.config/nah/history/`. The format is deliberately boring (std-only,
//! human-readable): a `key: header` block, then one length-prefixed message
//! block per line:
//!
//! ```text
//! nah-history 1
//! id: 1762109703-8f3a
//! unix: 1762109703
//! cwd: /home/user/project
//! model: local-model
//! messages: 2
//!
//! === user 15
//! hello, world! ?
//! === assistant 23
//! Hi! How can I help?
//! ```
//!
//! The byte length after the role makes parsing unambiguous even when a
//! message contains lines that look like markers.

use crate::error::CoreError;
use crate::provider::{ChatMessage, Role};
use std::collections::hash_map::DefaultHasher;
use std::hash::{Hash, Hasher};
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

/// Format marker + version, first line of every record.
pub const MAGIC: &str = "nah-history 1";

/// A saved conversation.
#[derive(Debug, Clone)]
pub struct SessionRecord {
    pub id: String,
    /// Creation time (UNIX seconds) - kept across resumes.
    pub unix: u64,
    pub cwd: String,
    pub model: String,
    pub messages: Vec<ChatMessage>,
}

/// Header-only view of a saved conversation (for listings).
#[derive(Debug, Clone)]
pub struct SessionInfo {
    pub id: String,
    pub unix: u64,
    pub cwd: String,
    pub model: String,
    pub messages: usize,
    /// First user message, collapsed to one short line.
    pub preview: String,
}

/// One search match inside a saved conversation.
#[derive(Debug, Clone)]
pub struct SearchHit {
    pub id: String,
    pub unix: u64,
    pub model: String,
    pub role: String,
    /// The matching message line, trimmed to one line.
    pub snippet: String,
}

/// Reads and writes session records in one directory.
pub struct HistoryStore {
    dir: PathBuf,
}

impl HistoryStore {
    pub fn new(dir: PathBuf) -> HistoryStore {
        HistoryStore { dir }
    }

    pub fn dir(&self) -> &Path {
        &self.dir
    }

    fn path_of(&self, id: &str) -> PathBuf {
        // ids are generated by new_session_id(); reject anything else so a
        // crafted id can never escape the history directory.
        let safe = !id.is_empty()
            && id.len() <= 64
            && id
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
        let name = if safe { id } else { "invalid" };
        self.dir.join(format!("{name}.txt"))
    }

    /// Write (or overwrite) a record. Sessions grow monotonically, so each
    /// save simply rewrites the file with the full transcript.
    pub fn save(&self, rec: &SessionRecord) -> Result<PathBuf, CoreError> {
        std::fs::create_dir_all(&self.dir)
            .map_err(|e| CoreError::Io(format!("cannot create {}: {e}", self.dir.display())))?;
        let mut out = String::new();
        out.push_str(MAGIC);
        out.push('\n');
        out.push_str(&format!("id: {}\n", rec.id));
        out.push_str(&format!("unix: {}\n", rec.unix));
        out.push_str(&format!("cwd: {}\n", rec.cwd));
        out.push_str(&format!("model: {}\n", rec.model));
        out.push_str(&format!("messages: {}\n", rec.messages.len()));
        for m in &rec.messages {
            out.push('\n');
            out.push_str(&format!("=== {} {}\n", m.role.as_str(), m.content.len()));
            out.push_str(&m.content);
            out.push('\n');
        }
        let path = self.path_of(&rec.id);
        std::fs::write(&path, out)
            .map_err(|e| CoreError::Io(format!("cannot write {}: {e}", path.display())))?;
        Ok(path)
    }

    /// Load one record by id. Malformed blocks are dropped (the whole
    /// blocks before them are kept); a wrong header is an error.
    pub fn load(&self, id: &str) -> Result<SessionRecord, CoreError> {
        let path = self.path_of(id);
        let text = std::fs::read_to_string(&path)
            .map_err(|e| CoreError::Io(format!("cannot read {}: {e}", path.display())))?;
        parse_record(&text)
            .filter(|r| r.id == id)
            .ok_or_else(|| CoreError::Config(format!("not a history record: {}", path.display())))
    }

    /// All readable records, newest first.
    pub fn list(&self) -> Vec<SessionInfo> {
        let mut out = Vec::new();
        let Ok(entries) = std::fs::read_dir(&self.dir) else {
            return out;
        };
        for entry in entries.flatten() {
            let name = entry.file_name();
            let Some(name) = name.to_str() else { continue };
            if !name.ends_with(".txt") {
                continue;
            }
            let Ok(text) = std::fs::read_to_string(entry.path()) else {
                continue;
            };
            let Some(rec) = parse_record(&text) else {
                continue;
            };
            out.push(SessionInfo {
                preview: preview_of(&rec.messages),
                messages: rec.messages.len(),
                id: rec.id,
                unix: rec.unix,
                cwd: rec.cwd,
                model: rec.model,
            });
        }
        out.sort_by(|a, b| b.unix.cmp(&a.unix).then_with(|| b.id.cmp(&a.id)));
        out
    }

    /// Case-insensitive substring search across all saved conversations,
    /// newest first. One hit per matching message (first matching line).
    pub fn search(&self, query: &str) -> Vec<SearchHit> {
        let needle = query.to_lowercase();
        let mut out = Vec::new();
        let Ok(entries) = std::fs::read_dir(&self.dir) else {
            return out;
        };
        for entry in entries.flatten() {
            let Ok(text) = std::fs::read_to_string(entry.path()) else {
                continue;
            };
            let Some(rec) = parse_record(&text) else {
                continue;
            };
            for m in &rec.messages {
                if !m.content.to_lowercase().contains(&needle) {
                    continue;
                }
                let line = m
                    .content
                    .lines()
                    .find(|l| l.to_lowercase().contains(&needle))
                    .unwrap_or("");
                out.push(SearchHit {
                    id: rec.id.clone(),
                    unix: rec.unix,
                    model: rec.model.clone(),
                    role: m.role.as_str().to_string(),
                    snippet: one_line(line, 90),
                });
            }
        }
        out.sort_by(|a, b| b.unix.cmp(&a.unix).then_with(|| b.id.cmp(&a.id)));
        out
    }
}

/// Unique, sortable session id: creation seconds + a short hash suffix.
pub fn new_session_id() -> String {
    let now = now_secs();
    let mut h = DefaultHasher::new();
    (now, std::process::id(), now_nanos()).hash(&mut h);
    format!("{now}-{:04x}", h.finish() & 0xffff)
}

pub fn now_secs() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0)
}

fn now_nanos() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.subsec_nanos() as u64)
        .unwrap_or(0)
}

/// Short relative age label ("42s ago", "5m ago", "3h ago", "2d ago").
pub fn ago_label(unix: u64) -> String {
    let d = now_secs().saturating_sub(unix);
    match d {
        0..=59 => format!("{d}s ago"),
        60..=3599 => format!("{}m ago", d / 60),
        3600..=86_399 => format!("{}h ago", d / 3600),
        _ => format!("{}d ago", d / 86_400),
    }
}

/// Collapse text to one trimmed line of at most `max` chars.
pub fn one_line(text: &str, max: usize) -> String {
    let flat = text.split_whitespace().collect::<Vec<_>>().join(" ");
    if flat.chars().count() <= max {
        flat
    } else {
        let cut: String = flat.chars().take(max.saturating_sub(1)).collect();
        format!("{cut}\u{2026}")
    }
}

/// First user message as a one-line preview.
fn preview_of(messages: &[ChatMessage]) -> String {
    let text = messages
        .iter()
        .find(|m| m.role == Role::User)
        .map(|m| m.content.as_str())
        .unwrap_or("");
    let line = text.lines().next().unwrap_or("");
    let preview = one_line(line, 48);
    if preview.is_empty() {
        "(no messages)".to_string()
    } else {
        preview
    }
}

/// Read one line at `*pos`, advancing past its newline.
fn read_line<'a>(b: &'a [u8], pos: &mut usize) -> Option<&'a str> {
    if *pos >= b.len() {
        return None;
    }
    let end = b[*pos..]
        .iter()
        .position(|&c| c == b'\n')
        .map(|i| *pos + i)
        .unwrap_or(b.len());
    let line = std::str::from_utf8(&b[*pos..end]).ok()?;
    *pos = (end + 1).min(b.len());
    Some(line)
}

/// Parse a record file. Tolerant: unknown header keys are ignored and a
/// malformed or truncated message block ends parsing with what we have.
fn parse_record(text: &str) -> Option<SessionRecord> {
    let b = text.as_bytes();
    let mut pos = 0usize;
    if read_line(b, &mut pos)?.trim_end() != MAGIC {
        return None;
    }
    let mut rec = SessionRecord {
        id: String::new(),
        unix: 0,
        cwd: String::new(),
        model: String::new(),
        messages: Vec::new(),
    };
    let mut in_header = true;
    while pos < b.len() {
        let line = read_line(b, &mut pos)?;
        if line.is_empty() {
            continue;
        }
        if let Some(marker) = line.strip_prefix("=== ") {
            in_header = false;
            let mut it = marker.split_whitespace();
            let (Some(role), Some(len)) = (it.next(), it.next()) else {
                break;
            };
            let (Some(role), Ok(len)) = (Role::parse(role), len.parse::<usize>()) else {
                break;
            };
            if pos + len > b.len() {
                break; // truncated file: keep whole blocks only
            }
            let Ok(content) = std::str::from_utf8(&b[pos..pos + len]) else {
                break;
            };
            rec.messages.push(ChatMessage {
                role,
                content: content.to_string(),
            });
            pos += len;
            if pos < b.len() && b[pos] == b'\n' {
                pos += 1;
            }
            continue;
        }
        if !in_header {
            break; // stray text after the last block
        }
        if let Some((key, value)) = line.split_once(": ") {
            match key {
                "id" => rec.id = value.to_string(),
                "unix" => rec.unix = value.parse().unwrap_or(0),
                "cwd" => rec.cwd = value.to_string(),
                "model" => rec.model = value.to_string(),
                _ => {}
            }
        }
    }
    if rec.id.is_empty() {
        return None;
    }
    Some(rec)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn dir(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(name);
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn rec(id: &str) -> SessionRecord {
        SessionRecord {
            id: id.to_string(),
            unix: 1000,
            cwd: "/tmp/proj".to_string(),
            model: "m1".to_string(),
            messages: vec![
                ChatMessage::user("hello\nsecond line"),
                ChatMessage::assistant("=== user 5\nlooks like a marker"),
                ChatMessage::user("\u{633}\u{644}\u{627}\u{645} \u{62f}\u{646}\u{6cc}\u{627}"),
            ],
        }
    }

    #[test]
    fn roundtrip_preserves_messages_verbatim() {
        let store = HistoryStore::new(dir("nah_test_hist_rt"));
        let r = rec("1000-abcd");
        store.save(&r).unwrap();
        let loaded = store.load("1000-abcd").unwrap();
        assert_eq!(loaded.id, r.id);
        assert_eq!(loaded.unix, r.unix);
        assert_eq!(loaded.cwd, r.cwd);
        assert_eq!(loaded.model, r.model);
        assert_eq!(loaded.messages.len(), 3);
        for (a, b) in loaded.messages.iter().zip(r.messages.iter()) {
            assert_eq!(a.role, b.role);
            assert_eq!(a.content, b.content);
        }
    }

    #[test]
    fn list_sorts_newest_first_and_previews() {
        let store = HistoryStore::new(dir("nah_test_hist_list"));
        let mut a = rec("1000-aaaa");
        a.unix = 1000;
        let mut b = rec("2000-bbbb");
        b.unix = 2000;
        b.messages = vec![ChatMessage::user("fix the   build")];
        store.save(&a).unwrap();
        store.save(&b).unwrap();
        let items = store.list();
        assert_eq!(items.len(), 2);
        assert_eq!(items[0].id, "2000-bbbb");
        assert_eq!(items[0].preview, "fix the build");
        assert_eq!(items[1].id, "1000-aaaa");
        assert_eq!(items[1].messages, 3);
    }

    #[test]
    fn search_is_case_insensitive_with_snippets() {
        let store = HistoryStore::new(dir("nah_test_hist_search"));
        store.save(&rec("1000-abcd")).unwrap();
        let hits = store.search("MARKER");
        assert_eq!(hits.len(), 1);
        assert_eq!(hits[0].role, "assistant");
        assert_eq!(hits[0].snippet, "looks like a marker");
        assert!(store.search("\u{633}\u{644}\u{627}\u{645}").len() == 1);
        assert!(store.search("nothing-here").is_empty());
    }

    #[test]
    fn load_missing_id_errors() {
        let store = HistoryStore::new(dir("nah_test_hist_missing"));
        assert!(store.load("9999-none").is_err());
    }

    #[test]
    fn parse_keeps_whole_blocks_before_truncation() {
        let text = format!("{MAGIC}\nid: 1000-abcd\nunix: 1000\ncwd: /x\nmodel: m\nmessages: 2\n\n=== user 5\nhello\n=== assistant 99\nthis is cut off");
        let rec = parse_record(&text).unwrap();
        assert_eq!(rec.messages.len(), 1);
        assert_eq!(rec.messages[0].content, "hello");
    }

    #[test]
    fn parse_rejects_wrong_magic_and_empty_id() {
        assert!(parse_record("not history\nid: 1\n").is_none());
        assert!(parse_record(&format!("{MAGIC}\nunix: 3\n")).is_none());
    }

    #[test]
    fn one_line_collapses_and_truncates() {
        assert_eq!(one_line(" a\n b\tc ", 20), "a b c");
        let s = one_line("abcdefghij", 5);
        assert_eq!(s.chars().count(), 5);
        assert!(s.ends_with('\u{2026}'));
    }

    #[test]
    fn ago_label_covers_scales() {
        assert!(ago_label(now_secs()).ends_with("s ago"));
        assert!(ago_label(now_secs().saturating_sub(300)).ends_with("m ago"));
        assert!(ago_label(now_secs().saturating_sub(7200)).ends_with("h ago"));
        assert!(ago_label(now_secs().saturating_sub(200_000)).ends_with("d ago"));
    }

    #[test]
    fn ids_are_unique_and_path_safe() {
        let a = new_session_id();
        let b = new_session_id();
        assert_ne!(a, b);
        let store = HistoryStore::new(dir("nah_test_hist_ids"));
        // a hostile id must never leave the history directory
        let p = store.path_of("../../evil");
        assert_eq!(p.parent(), Some(store.dir()));
    }
}
